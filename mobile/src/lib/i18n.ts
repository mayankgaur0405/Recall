export type TranslationKey = keyof typeof translations.en

export async function getSavedLanguage(): Promise<LanguageCode> {
  try {
    const raw = await SecureStore.getItemAsync(LANG_KEY)
    if (raw && raw in translations) {
      return raw as LanguageCode
    }
  } catch {}
  return 'en'
}

export async function setSavedLanguage(code: LanguageCode): Promise<void> {
  try {
    await SecureStore.setItemAsync(LANG_KEY, code)
  } catch {}
}
